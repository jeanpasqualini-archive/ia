    /**
     * Write a line into a buffer of pixels, and return the column it ended on.
     *
     * The buffer is the same one the map is drawn into, which is the whole
     * point: text is not a second mechanism, it is more pixels.
     */
    public static function write(
        Pixels $pixels,
        int $x,
        int $y,
        string $text,
        int $colour,
        int $scale = 1,
    ): int {
        $pen = $x;

        foreach (preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY) ?: [] as $char) {
            $glyph = self::GLYPHS[$char] ?? self::GLYPHS['?'];

            foreach ($glyph as $row => $bits) {
                for ($column = 0; $column < self::WIDTH; $column++) {
                    if (0 === ($bits & (1 << (self::WIDTH - 1 - $column)))) {
                        continue;
                    }

                    // Clipping lives in Pixels, so a string one character
                    // too long is dropped rather than reappearing at the
                    // start of the next row.
                    $pixels->rect(
                        $pen + $column * $scale,
                        $y + $row * $scale,
                        $scale,
                        $scale,
                        $colour
                    );
                }
            }

            $pen += self::ADVANCE * $scale;
        }

        return $pen;
    }

    /** Width a string will take, so a layout can be worked out before drawing. */
    public static function widthOf(string $text, int $scale = 1): int
    {
        return mb_strlen($text) * self::ADVANCE * $scale;
    }
}
