/**
 * A 5x7 bitmap font, drawn into a buffer of pixels.
 *
 * **This is the answer to "SDL cannot write a single character".** It does not
 * need to: the window demo already composes its own buffer of pixels in PHP
 * and hands the whole thing over in one call. Text is more pixels in the same
 * buffer. No SDL_ttf, no second library to find at runtime, no second header
 * to transcribe against an ABI that would corrupt memory if it were wrong.
 *
 * The whole typeface is **665 bytes** — ninety five glyphs of seven rows, five
 * bits each, the high bit being the leftmost column. That is the entire cost
 * of the thing that was supposed to be the obstacle.
 *
